"""Generate `docs/datasets/` from catalog.yaml (how each dataset is downloaded) and
docs/datasets.yaml (its description): an index, one page per repository, and one page per
dataset (`docs/datasets/<id>.md`) with its facts, links, access steps and the command that
gets it. Never edit those files by hand; edit the two YAML files."""

from __future__ import annotations

import posixpath
from collections import Counter, defaultdict
from pathlib import Path

from biosignal_data.catalog.loader import Catalog, Infos
from biosignal_data.catalog.models import AccessTier, Dataset, DatasetInfo

HEADER = (
    "<!-- Generated by `biosignal-data dev docs` from catalog.yaml and docs/datasets.yaml. "
    "Do not edit by hand. -->\n\n"
)

TIER_TEXT = {
    AccessTier.OPEN: "Open: anonymous download",
    AccessTier.REGISTRATION: "Registration: free account, token or license click-through",
    AccessTier.APPLICATION: "Application: a request that someone reviews",
    AccessTier.CREDENTIALED: "Credentialed: approval plus training or identity checks",
    AccessTier.UNAVAILABLE: "Unavailable: known, but not obtainable",
}

TIER_EXPLANATION = {
    AccessTier.OPEN: "Anyone can download the data. You do not need an account.",
    AccessTier.REGISTRATION: (
        "You need a free account or an access token, or you must accept a license on the "
        "provider's site. Nobody reviews this step."
    ),
    AccessTier.APPLICATION: (
        "You must send a request (for example a form, a data use agreement or a fee). "
        "A person at the provider reviews it before you get access."
    ),
    AccessTier.CREDENTIALED: (
        "You need approval and proof of training or identity (for example a CITI "
        "certificate and a signed data use agreement)."
    ),
    AccessTier.UNAVAILABLE: (
        "The dataset is known, but you cannot get it now (for example, it is private or "
        "the provider no longer gives it out)."
    ),
}

# The same text for every value that the descriptions do not know yet, so it is easy to find.
UNKNOWN = "_unknown (to be filled)_"


def page_path(dataset_id: str) -> str:
    """Path of a dataset's page, relative to `docs/datasets/`."""
    return f"{dataset_id}.md"


def _link(target: str, start: str) -> str:
    """Relative link from the page `start` to the page `target` (both relative to the root)."""
    return posixpath.relpath(target, posixpath.dirname(start) or ".")


def _hours(d: DatasetInfo) -> str:
    if d.stats.hours is None:
        return ""
    return ("~" if d.stats.hours_estimated else "") + f"{d.stats.hours:,.0f}"


def _download_command(d: Dataset) -> str:
    if d.source.type == "manual":
        return (
            f"biosignal-data import {d.id} <folder you downloaded into> "
            "--version <label> --dest s3://<bucket>"
        )
    command = f"biosignal-data download {d.id} --dest s3://<bucket>"
    if d.source.type == "s3" and getattr(d.source, "prefix", None) is None:
        return f"# first write the key prefix into catalog.yaml ({d.id}: source.prefix)\n{command}"
    return command


def _section(entry: Dataset, d: DatasetInfo) -> str:
    lines = [f"## {d.name}", "", f"[`{d.id}`]({page_path(d.id)})", ""]
    facts = [
        ("Signals", ", ".join(d.signals)),
        ("Access", TIER_TEXT[d.access.tier]),
        ("License", entry.license or "see homepage"),
        ("Source", entry.source.type),
        ("Subjects", f"{d.stats.subjects:,}" if d.stats.subjects else ""),
        ("Hours", _hours(d)),
        ("Homepage", f"<{d.homepage}>" if d.homepage else ""),
        ("Download tested", "yes" if d.download_verified else "not yet"),
    ]
    lines += ["| | |", "| --- | --- |"] + [f"| {k} | {v} |" for k, v in facts if v]
    if d.access.steps:
        lines += ["", "**Before downloading**", ""]
        lines += [f"{i}. {step}" for i, step in enumerate(d.access.steps, 1)]
    if d.access.credentials:
        lines += ["", "**Credentials**: " + ", ".join(f"`{c}`" for c in d.access.credentials)]
    lines += ["", "```bash", _download_command(entry), "```"]
    if d.related:
        lines += ["", "Related: " + ", ".join(f"[`{r}`]({page_path(r)})" for r in d.related)]
    if d.stats.note or d.notes:
        lines += ["", "Notes:", ""] + [
            f"- {n}" for n in ([d.stats.note] if d.stats.note else []) + d.notes
        ]
    return "\n".join(lines) + "\n"


def _number(value: float) -> str:
    return f"{value:,.2f}".rstrip("0").rstrip(".")


def _size(size_bytes: int) -> str:
    value = float(size_bytes)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1000 or unit == "TB":
            break
        value /= 1000
    return f"{_number(value)} {unit} ({size_bytes:,} bytes)"


def _or_unknown(value: object) -> str:
    return UNKNOWN if value is None else str(value)


def _list(items: list[str], empty: str) -> list[str]:
    return [f"- {item}" for item in items] if items else [empty]


def _dataset_page(entry: Dataset, d: DatasetInfo, known: set[str]) -> str:
    """One page per dataset. Every page has the same sections in the same order; a value
    that the files do not know is shown as UNKNOWN."""
    here = page_path(d.id)
    stats = d.stats
    hours = None
    if stats.hours is not None:
        hours = _number(stats.hours) + (" (estimated)" if stats.hours_estimated else "")
    facts = [
        ("ID", f"`{d.id}`"),
        ("Repository", f"[{d.repository}]({_link(f'{d.repository}.md', here)})"),
        ("Signals", ", ".join(d.signals)),
        ("Access", TIER_TEXT[d.access.tier]),
        ("License", _or_unknown(entry.license)),
        ("Subjects", _or_unknown(None if stats.subjects is None else f"{stats.subjects:,}")),
        ("Recordings", _or_unknown(None if stats.recordings is None else f"{stats.recordings:,}")),
        ("Hours", _or_unknown(hours)),
        ("Size", _or_unknown(None if stats.size_bytes is None else _size(stats.size_bytes))),
        ("Source type", entry.source.type),
        ("Download tested", "yes" if d.download_verified else "not yet"),
    ]
    lines = [HEADER + f"# {d.name}", ""]
    lines += ["| | |", "| --- | --- |"] + [f"| {k} | {v} |" for k, v in facts]

    lines += ["", "## Access", "", f"{TIER_TEXT[d.access.tier]}. {TIER_EXPLANATION[d.access.tier]}"]

    lines += ["", "## Links", ""]
    lines.append(f"- Homepage: {f'<{d.homepage}>' if d.homepage else UNKNOWN}")
    if entry.source.type == "manual":
        url = getattr(entry.source, "url", None)
        lines.append(f"- Download page: {f'<{url}>' if url else UNKNOWN}")
    if d.references:
        lines.append("- References:")
        lines += [f"  - <{r}>" for r in d.references]
    else:
        lines.append(f"- References: {UNKNOWN}")

    lines += ["", "## Before downloading", ""]
    if d.access.steps:
        lines += [f"{i}. {step}" for i, step in enumerate(d.access.steps, 1)]
    else:
        lines.append("No manual steps.")

    lines += ["", "## Credentials", ""]
    lines += _list(
        [f"`{c}`" for c in d.access.credentials], "None. The tool reads no credentials for it."
    )

    lines += ["", "## Get the data", ""]
    if d.access.tier is AccessTier.UNAVAILABLE:
        lines += ["You cannot get this dataset now. If you get the files, the command is:", ""]
    elif entry.source.type == "manual":
        lines += [
            "Download the files into a folder as the steps above say, then import the folder:",
            "",
        ]
    lines += ["```bash", _download_command(entry), "```"]

    lines += ["", "## Related datasets", ""]
    lines += _list(
        [f"[`{r}`]({_link(page_path(r), here)})" if r in known else f"`{r}`" for r in d.related],
        "None.",
    )

    lines += ["", "## Notes", ""]
    lines += _list(([stats.note] if stats.note else []) + d.notes, "None.")
    return "\n".join(lines) + "\n"


def render(catalog: Catalog, infos: Infos) -> dict[str, str]:
    """All pages, keyed by their path relative to `docs/datasets/` (with `/`). The two files
    must list the same datasets (see `check_pair`)."""
    by_repo: dict[str, list[DatasetInfo]] = defaultdict(list)
    for d in infos:
        by_repo[d.repository].append(d)

    pages: dict[str, str] = {}
    for repo, items in sorted(by_repo.items()):
        items.sort(key=lambda d: d.id)
        body = [HEADER + f"# {repo}\n", f"{len(items)} datasets.\n"]
        body += [_section(catalog.get(d.id), d) for d in items]
        pages[f"{repo}.md"] = "\n".join(body)

    known = {d.id for d in infos}
    for d in infos:
        pages[page_path(d.id)] = _dataset_page(catalog.get(d.id), d, known)

    tiers = Counter(d.access.tier for d in infos)
    index = [
        HEADER + "# Datasets\n",
        f"{len(infos)} datasets in {len(by_repo)} repositories.\n",
        "| Access | Datasets |",
        "| --- | --- |",
    ]
    index += [f"| {TIER_TEXT[t]} | {tiers[t]} |" for t in AccessTier if tiers[t]]
    index += ["", "| Repository | Datasets | Source types |", "| --- | --- | --- |"]
    for repo, items in sorted(by_repo.items()):
        kinds = ", ".join(sorted({catalog.get(d.id).source.type for d in items}))
        index.append(f"| [{repo}]({repo}.md) | {len(items)} | {kinds} |")
    index += ["", "## All datasets", ""]
    index += ["| Dataset | ID | Signals | Access |", "| --- | --- | --- | --- |"]
    for d in sorted(infos, key=lambda d: d.id):
        name = d.name.replace("|", "\\|")
        index.append(
            f"| [{name}]({page_path(d.id)}) | `{d.id}` | {', '.join(d.signals)} | {d.access.tier} |"
        )
    pages["README.md"] = "\n".join(index) + "\n"
    return pages


def existing_pages(out: Path) -> set[str]:
    """Every `.md` file under `out`, as paths relative to `out` (with `/`)."""
    if not out.is_dir():
        return set()
    return {p.relative_to(out).as_posix() for p in out.rglob("*.md")}


def write_docs(catalog: Catalog, infos: Infos, out: Path, *, check: bool = False) -> list[str]:
    """Write pages to `out` and delete pages that are no longer generated. With `check`,
    write nothing and return the stale file names."""
    pages = render(catalog, infos)
    stale = [
        name
        for name, text in pages.items()
        if not (out / name).is_file() or (out / name).read_text(encoding="utf-8") != text
    ]
    existing = existing_pages(out)
    stale += sorted(existing - set(pages))
    if check:
        return stale
    out.mkdir(parents=True, exist_ok=True)
    for name in existing - set(pages):
        (out / name).unlink()
    for folder in sorted((p for p in out.rglob("*") if p.is_dir()), reverse=True):
        if not any(folder.iterdir()):
            folder.rmdir()
    for name, text in pages.items():
        path = out / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
    return stale
