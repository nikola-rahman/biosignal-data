"""Generate `docs/datasets/` from the catalog: an index plus one page per repository with
each dataset's access steps and the command that downloads it. Never edit those files by hand."""

from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path

from biosignal_data.catalog.loader import Catalog
from biosignal_data.catalog.models import AccessTier, Dataset

HEADER = "<!-- Generated by `biosignal-data dev docs` from catalog/. Do not edit by hand. -->\n\n"

TIER_TEXT = {
    AccessTier.OPEN: "Open: anonymous download",
    AccessTier.REGISTRATION: "Registration: free account, token or license click-through",
    AccessTier.APPLICATION: "Application: a request that someone reviews",
    AccessTier.CREDENTIALED: "Credentialed: approval plus training or identity checks",
    AccessTier.UNAVAILABLE: "Unavailable: known, but not obtainable",
}


def _hours(d: Dataset) -> str:
    if d.stats.hours is None:
        return ""
    return ("~" if d.stats.hours_estimated else "") + f"{d.stats.hours:,.0f}"


def _download_command(d: Dataset) -> str:
    if d.source.type == "manual":
        return (
            f"biosignal-data import {d.id} <folder you downloaded into> "
            "--version <label> --dest s3://<bucket>"
        )
    command = f"biosignal-data download {d.id} --dest s3://<bucket>"
    if d.source.type == "s3" and getattr(d.source, "prefix", None) is None:
        return f"# first write the key prefix into catalog/{d.id}.yaml (source.prefix)\n{command}"
    return command


def _section(d: Dataset) -> str:
    lines = [f"## {d.name}", "", f"`{d.id}`", ""]
    facts = [
        ("Signals", ", ".join(d.signals)),
        ("Access", TIER_TEXT[d.access.tier]),
        ("License", d.access.license or "see homepage"),
        ("Source", d.source.type),
        ("Subjects", f"{d.stats.subjects:,}" if d.stats.subjects else ""),
        ("Hours", _hours(d)),
        ("Homepage", f"<{d.homepage}>" if d.homepage else ""),
        ("Download tested", "yes" if d.download_verified else "not yet"),
    ]
    lines += ["| | |", "| --- | --- |"] + [f"| {k} | {v} |" for k, v in facts if v]
    if d.access.steps:
        lines += ["", "**Before downloading**", ""]
        lines += [f"{i}. {step}" for i, step in enumerate(d.access.steps, 1)]
    if d.access.credentials:
        lines += ["", "**Credentials**: " + ", ".join(f"`{c}`" for c in d.access.credentials)]
    lines += ["", "```bash", _download_command(d), "```"]
    if d.related:
        lines += ["", "Related: " + ", ".join(f"`{r}`" for r in d.related)]
    if d.stats.note or d.notes:
        lines += ["", "Notes:", ""] + [
            f"- {n}" for n in ([d.stats.note] if d.stats.note else []) + d.notes
        ]
    return "\n".join(lines) + "\n"


def render(catalog: Catalog) -> dict[str, str]:
    by_repo: dict[str, list[Dataset]] = defaultdict(list)
    for d in catalog:
        by_repo[d.repository].append(d)

    pages: dict[str, str] = {}
    for repo, items in sorted(by_repo.items()):
        items.sort(key=lambda d: d.id)
        body = [HEADER + f"# {repo}\n", f"{len(items)} datasets.\n"]
        body += [_section(d) for d in items]
        pages[f"{repo}.md"] = "\n".join(body)

    tiers = Counter(d.access.tier for d in catalog)
    index = [
        HEADER + "# Datasets\n",
        f"{len(catalog)} catalog entries in {len(by_repo)} repositories.\n",
        "| Access | Datasets |",
        "| --- | --- |",
    ]
    index += [f"| {TIER_TEXT[t]} | {tiers[t]} |" for t in AccessTier if tiers[t]]
    index += ["", "| Repository | Datasets | Source types |", "| --- | --- | --- |"]
    for repo, items in sorted(by_repo.items()):
        kinds = ", ".join(sorted({d.source.type for d in items}))
        index.append(f"| [{repo}]({repo}.md) | {len(items)} | {kinds} |")
    pages["README.md"] = "\n".join(index) + "\n"
    return pages


def write_docs(catalog: Catalog, out: Path, *, check: bool = False) -> list[str]:
    """Write pages to `out`. With `check`, write nothing and return the stale file names."""
    pages = render(catalog)
    stale = [
        name
        for name, text in pages.items()
        if not (out / name).is_file() or (out / name).read_text(encoding="utf-8") != text
    ]
    existing = {p.name for p in out.glob("*.md")} if out.is_dir() else set()
    stale += sorted(existing - set(pages))
    if check:
        return stale
    out.mkdir(parents=True, exist_ok=True)
    for name in existing - set(pages):
        (out / name).unlink()
    for name, text in pages.items():
        (out / name).write_text(text, encoding="utf-8")
    return stale
